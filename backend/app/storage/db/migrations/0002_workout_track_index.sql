-- Трек читается страницами по ключу (track_id, date, id) — ровно в этом порядке
-- идёт и предикат курсора, и сортировка. Без индекса каждая страница сканирует
-- всю таблицу и строит временное дерево на ORDER BY, то есть постраничность
-- перестаёт что-либо экономить.
CREATE INDEX idx_workout_track_date ON workout(track_id, date DESC, id DESC);
